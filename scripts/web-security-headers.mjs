export const STARRY_ID_ORIGINS=['https://id.starry.phd','https://starry-id-staging.starry-phd.workers.dev'];
// Web sign-in is a full-page redirect to the Starry relay (starry-phd/id guide §11.2, 2026-11-03):
// no Google or Apple script, style or frame is ever loaded by this site.

/** null/empty → guest site; an allow-listed Starry ID origin → login-enabled site; anything else throws. */
export function resolveStarryOrigin(raw){
 const value=String(raw??'').trim().replace(/\/+$/,'');
 if(!value)return null;
 if(!STARRY_ID_ORIGINS.includes(value))throw Error('EXPO_PUBLIC_STARRY_ID_API_BASE_URL is not an allow-listed Starry ID origin');
 return value;
}

/** CSP for this build: guest by default; with sign-in only the Starry ID origin is added. */
export function cspDirectivesFor(starryOrigin=null){
 const d=Object.fromEntries(Object.entries(CSP_DIRECTIVES).map(([k,v])=>[k,[...v]]));
 if(!starryOrigin)return d;
 d['connect-src'].push(starryOrigin); // Starry ID API (nonce, sign-in, /v1/me)
 d['img-src'].push(starryOrigin); // member avatars served by Starry ID
 return d;
}

export function headersFileFor(starryOrigin=null){
 const csp=Object.entries(cspDirectivesFor(starryOrigin)).map(([k,v])=>k+' '+v.join(' ')).join('; ');
 return ['# Security headers for the static Web shell (Cloudflare Workers Static Assets).',
  '# GENERATED by scripts/write-web-headers.mjs from scripts/web-security-headers.mjs — do not edit by hand.',
  '# API responses (/api/*, /health) are produced by the Worker and set their own headers.',
  '# CSP is ENFORCED; the post-deploy visual check reports any blocked resource. See docs/138-web-security-headers.md.',
  starryOrigin?'# Starry ID sign-in ENABLED for '+starryOrigin+' (relay redirect; no Google/Apple scripts).':'# Guest site: no third-party sources.',
  '/*',
  '  Content-Security-Policy: '+csp,
  ...Object.entries(FIXED_HEADER_NAMES).map(([lower,name])=>'  '+name+': '+FIXED_HEADERS[lower]),
  ''].join('\n');
}

export const FIXED_HEADERS={
 'x-content-type-options':'nosniff',
 'x-frame-options':'DENY',
 'referrer-policy':'strict-origin-when-cross-origin',
 'permissions-policy':'camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()',
 'cross-origin-opener-policy':'same-origin-allow-popups'
};

const FIXED_HEADER_NAMES={'x-content-type-options':'X-Content-Type-Options','x-frame-options':'X-Frame-Options',
 'referrer-policy':'Referrer-Policy','permissions-policy':'Permissions-Policy','cross-origin-opener-policy':'Cross-Origin-Opener-Policy'};

export function parseCsp(value){
 const out=new Map();
 for(const part of String(value??'').split(';')){
  const [name,...sources]=part.trim().split(/\s+/).filter(Boolean);
  if(!name)continue;
  if(out.has(name))throw Error('Duplicate CSP directive '+name);
  out.set(name.toLowerCase(),sources);
 }
 return out;
}

/** `get(name)` returns a header value or null; mode is 'report-only' or 'enforce'. */
export function validateSecurityHeaders(get,mode,starryOrigin=null){
 const cspName=mode==='enforce'?'content-security-policy':'content-security-policy-report-only';
 const other=mode==='enforce'?'content-security-policy-report-only':'content-security-policy';
 const csp=get(cspName);
 if(!csp)throw Error('Missing '+cspName);
 if(get(other))throw Error('Unexpected '+other+' while in '+mode+' mode');
 const parsed=parseCsp(csp);
 const expected=cspDirectivesFor(starryOrigin);
 for(const [name,sources] of Object.entries(expected)){
  const actual=parsed.get(name);
  if(!actual||actual.join(' ')!==sources.join(' '))throw Error('CSP '+name+' must be '+sources.join(' ')+', got '+(actual?.join(' ')??'missing'));
 }
 for(const name of parsed.keys())if(!(name in expected))throw Error('Unexpected CSP directive '+name);
 for(const [name,value] of Object.entries(FIXED_HEADERS))
  if(get(name)!==value)throw Error(name+' must be "'+value+'", got "'+get(name)+'"');
 return {mode,directives:parsed.size};
}

/** Parse the Cloudflare `_headers` file block for `/*` into lower-case header pairs. */
export function headersFileRules(text){
 const lines=String(text).split(/\r?\n/).filter(line=>line.trim()&&!line.trim().startsWith('#'));
 const rules=new Map();let current=null;
 for(const line of lines){
  if(!/^\s/.test(line)){current=line.trim();rules.set(current,new Map());continue;}
  if(!current)throw Error('Header outside a path block');
  const i=line.indexOf(':');
  rules.get(current).set(line.slice(0,i).trim().toLowerCase(),line.slice(i+1).trim());
 }
 return rules;
}
